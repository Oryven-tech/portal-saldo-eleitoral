"""Create the deterministic, visibly fictitious PDF embedded in the demo only."""
from base64 import b64encode
from hashlib import sha256
from io import BytesIO
from pathlib import Path

from reportlab.lib.colors import HexColor
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen.canvas import Canvas

root = Path(__file__).resolve().parent.parent
output = BytesIO()
pdf = Canvas(output, pagesize=A4, invariant=1, pageCompression=1)
pdf.setTitle("Exemplo fictício - Portal Saldo Eleitoral")
pdf.setAuthor("Portal Saldo Eleitoral - Demonstração")
sections = [
    ("Treinamento", "Exemplo de anexo para conferência de treinamento."),
    ("Primeiro turno", "Exemplo de anexo para conferência do primeiro turno."),
    ("Informações complementares", "Exemplo de página complementar do mesmo envio."),
]
for number, (title, description) in enumerate(sections, 1):
    pdf.setFillColor(HexColor("#244d40"))
    pdf.setFont("Helvetica-Bold", 19)
    pdf.drawString(48, 780, "PORTAL SALDO ELEITORAL")
    pdf.setFillColor(HexColor("#9b4d35"))
    pdf.setFont("Helvetica-Bold", 15)
    pdf.drawString(48, 742, "EXEMPLO FICTÍCIO - SEM VALIDADE")
    pdf.setFillColor(HexColor("#2d3530"))
    pdf.setFont("Helvetica-Bold", 17)
    pdf.drawString(48, 680, title)
    pdf.setFont("Helvetica", 12)
    for line, y in zip([
        description,
        "Arquivo criado apenas para testar a análise de comprovantes.",
        "Não comprova serviço eleitoral e não deve ser usado oficialmente.",
        "Não contém dados pessoais nem assinatura de autoridade.",
    ], [642, 610, 578, 546]):
        pdf.drawString(48, y, line)
    pdf.setStrokeColor(HexColor("#e4e6dc"))
    pdf.line(48, 76, 547, 76)
    pdf.setFont("Helvetica", 10)
    pdf.drawString(48, 55, "Demonstração independente dos dados da escola")
    pdf.drawRightString(547, 55, f"Página {number} de 3")
    pdf.showPage()
pdf.save()
data = output.getvalue()
artifact = root / ".artifacts" / "demo-comprovante-exemplo.pdf"
artifact.write_bytes(data)
module = "// Generated by scripts/create-demo-evidence.py; synthetic data only.\n"
module += f"export const DEMO_EVIDENCE_SIZE = {len(data)};\n"
module += f"export const DEMO_EVIDENCE_HASH = '{sha256(data).hexdigest()}';\n"
module += f"const encoded = '{b64encode(data).decode()}';\n"
module += "export function createDemoEvidence(): Blob {\n"
module += "  const bytes = Uint8Array.from(atob(encoded), (char) => char.charCodeAt(0));\n"
module += "  return new Blob([bytes], { type: 'application/pdf' });\n}\n"
(root / "src" / "demo-evidence.ts").write_text(module, encoding="utf-8")
print(f"PDF fictício gerado: {len(data)} bytes, 3 páginas.")
